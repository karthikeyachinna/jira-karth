"""Publish the release notes to Confluence Cloud (create or update a page, attach the PDF)."""
from __future__ import annotations

from pathlib import Path

import requests

from .config import Settings


def publish(settings: Settings, title: str, body_xhtml: str, pdf: Path | None) -> str:
    base = f"{settings.jira_base_url}/wiki"
    s = requests.Session()
    s.auth = (settings.jira_email, settings.jira_token)
    s.headers.update({"Accept": "application/json"})

    r = s.get(f"{base}/api/v2/spaces", params={"keys": settings.confluence_space_key}, timeout=60)
    r.raise_for_status()
    spaces = r.json().get("results", [])
    if not spaces:
        raise SystemExit(f"Confluence space {settings.confluence_space_key!r} not found")
    space_id = spaces[0]["id"]
    parent_id = _resolve_parent(s, base, settings.confluence_parent_page_id,
                                spaces[0].get("homepageId"))

    r = s.get(f"{base}/api/v2/pages", params={"space-id": space_id, "title": title}, timeout=60)
    r.raise_for_status()
    existing = r.json().get("results", [])
    body = {"representation": "storage", "value": body_xhtml}

    if existing:
        page_id = existing[0]["id"]
        version = s.get(f"{base}/api/v2/pages/{page_id}", timeout=60).json()["version"]["number"]
        r = s.put(f"{base}/api/v2/pages/{page_id}", timeout=60, json={
            "id": page_id, "status": "current", "title": title, "body": body,
            "version": {"number": version + 1, "message": "Regenerated by GoCD jira-release-notes"}})
    else:
        payload = {"spaceId": space_id, "status": "current", "title": title, "body": body}
        if parent_id:
            payload["parentId"] = parent_id
        r = s.post(f"{base}/api/v2/pages", json=payload, timeout=60)
    if not r.ok:
        raise SystemExit(f"Confluence {r.status_code}: {r.text[:400]}")
    page = r.json()
    page_id = page["id"]

    if pdf and pdf.is_file():
        with pdf.open("rb") as fh:
            ar = s.put(f"{base}/rest/api/content/{page_id}/child/attachment",
                       headers={"X-Atlassian-Token": "no-check"},
                       files={"file": (pdf.name, fh, "application/pdf")}, timeout=120)
        print(f"[confluence] PDF attachment: {ar.status_code}")

    url = f"{base}{page.get('_links', {}).get('webui', f'/pages/{page_id}')}"
    print(f"[confluence] published: {url}")
    return url


def _resolve_parent(s: requests.Session, base: str, wanted: str, homepage: str | None) -> str | None:
    """CONFLUENCE_PARENT_PAGE_ID may be a page or a folder. If it no longer exists (e.g. it was
    an unpublished draft or got deleted), publish under the space home page instead of failing."""
    if not wanted:
        return homepage
    for kind in ("pages", "folders"):
        if s.get(f"{base}/api/v2/{kind}/{wanted}", timeout=60).ok:
            return wanted
    print(f"[confluence] WARNING: parent {wanted} not found (deleted or still a draft) - "
          f"publishing under the space home page {homepage}. Fix CONFLUENCE_PARENT_PAGE_ID.")
    return homepage
